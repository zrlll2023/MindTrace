/**
 * 出网脱敏（spec §8）：在把文本发送给 LLM 前，去除/替换个人标识信息。
 * 规则式（不用 AI），保证确定性与零成本。
 */

export function desensitizeText(text: string): string {
  let t = text

  // 1. 链接：只保留域名提示
  t = t.replace(/https?:\/\/([A-Za-z0-9.-]+)[^\s，。；、"')\]]*/g, (_m, host: string) => `[链接:${host}]`)

  // 2. 邮箱
  t = t.replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, '[邮箱]')

  // 3. 身份证（18 位，含校验位 X）
  t = t.replace(/\b\d{17}[\dXx]\b/g, '[证件号]')

  // 4. 手机号（1 开头的 11 位）
  t = t.replace(/\b1[3-9]\d{9}\b/g, '[手机号]')

  // 5. 社交账号：@xxx（字母数字下划线，2 位以上）
  t = t.replace(/@([A-Za-z0-9_]{2,})/g, '[账号]')

  // 6. 「和/跟/被/找/与 + 人名」模式（人名后跟标点/常见动词边界；避免误伤关系称谓）
  t = t.replace(
    /(和|跟|被|找|与)([\u4e00-\u9fa5]{2,3}?)(?=[，。；！？、]|$|吃了|骂了|说了|聊了|打了|见了|吵了|哭了|笑了|约了|分手|吵架|打电话|开会|吃饭)/g,
    (match, prep: string, name: string) => {
      const WHITELIST = new Set([
        '导师', '妈妈', '爸爸', '朋友', '同学', '老师', '同事', '老板', '领导',
        '室友', '家人', '客户', '对象', '自己', '大家', '别人', '他们', '她们',
        '我们', '师兄', '师姐', '师弟', '师妹', '孩子', '女友', '男友',
        '老婆', '老公', '父母', '大夫', '医生', '护士', '对方', '其他'
      ])
      if (WHITELIST.has(name)) return match
      return prep + '[某人]'
    }
  )

  return t
}
